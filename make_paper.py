def three_line(headers, rows, size=10.5):
    """三线表：顶线/底线 1.5pt，表头下线 0.5pt，无竖线、无内部横线"""
    t = doc.add_table(rows=len(rows) + 1, cols=len(headers))
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    tblPr = t._tbl.tblPr
    borders = OxmlElement('w:tblBorders')
    for tag, sz in (('top', '12'), ('bottom', '12')):
        el = OxmlElement('w:' + tag)
        el.set(qn('w:val'), 'single'); el.set(qn('w:sz'), sz)
        el.set(qn('w:space'), '0'); el.set(qn('w:color'), '000000')
        borders.append(el)
    for tag in ('left', 'right', 'insideH', 'insideV'):
        el = OxmlElement('w:' + tag)
        el.set(qn('w:val'), 'none'); el.set(qn('w:sz'), '0'); el.set(qn('w:space'), '0')
        borders.append(el)
    tblPr.append(borders)
    for j, htxt in enumerate(headers):
        _cell_text(t.rows[0].cells[j], htxt, bold=True, size=size)
    for cell in t.rows[0].cells:
        tcPr = cell._tc.get_or_add_tcPr()
        tcB = OxmlElement('w:tcBorders')
        b = OxmlElement('w:bottom')
        b.set(qn('w:val'), 'single'); b.set(qn('w:sz'), '4')
        b.set(qn('w:space'), '0'); b.set(qn('w:color'), '000000')
        tcB.append(b)
        tcPr.append(tcB)
    for i, row in enumerate(rows):
        for j, v in enumerate(row):
            _cell_text(t.rows[i + 1].cells[j], v, size=size)
    return t


