# ================= 五、问题一的模型建立与求解 =================
h1('五、基于日循环线性规划的典型日购电策略（问题一）')
h2('5.1 决策变量')
body('将每天 24 小时离散为 T = 144 个时段，每时段 Δt = 10 min = 1/6 h。对每个时段 t = 1, 2, …, 144，'
     '设定如下决策变量：计划购电量 buy_t（kWh）、储能充电量 ch_t（kWh）、储能放电量 dis_t（kWh）；'
     '为刻画储能状态，引入辅助变量 SOC_t（t = 1, 2, …, 145），表示第 t 时段初（即时刻 t−1 个 10 分钟处）'
     '的储能设备储电量。全部决策变量共 3×144 + 145 = 577 个。')
h2('5.2 目标函数')
body('问题一要求在不降低供电水平的前提下尽可能节省购电费用。充电量与放电量本身不直接产生费用'
     '（其成本已通过购电环节计入），故目标函数为全天计划购电费用最小：')
eq('min  C = Σ_{t=1}^{144}  p_t · buy_t', 1)
body('其中 p_t 为附件 1 给出的第 t 时段外网电价（元/kWh），buy_t 为该时段的计划购电量（kWh）。')
h2('5.3 约束条件')
body('（1）功率平衡约束（允许弃光）。题目要求微网提供的电能不可低于小区负载。'
     '每个时段的供电侧包括外网购电 buy_t、光伏发电 PV_t·Δt 与储能放电 dis_t，'
     '用电侧包括小区负载 L_t·Δt 与储能充电 ch_t。允许弃光意味着供电可以不小于需求，故有')
eq('buy_t + PV_t·Δt + dis_t ≥ L_t·Δt + ch_t,  t = 1, 2, …, 144', 2)
body('该约束保证任何时段微网对小区的供电水平不低于负载，同时赋予光伏“用不完可弃”的灵活性。')
body('（2）储能荷电状态动态约束。充放电效率均为 η = 0.9：每充入 ch_t 电量，储能实际增加 η·ch_t；'
     '每向外放出 dis_t 电量，储能实际减少 dis_t/η。因此 SOC 的时段递推关系为')
eq('SOC_{t+1} = SOC_t + η·ch_t − dis_t/η,  t = 1, 2, …, 144', 3)
body('（3）储能电量上下限约束。为避免过度充放电，储能电量须保持在最大容量 12000 kWh 的 '
     '10%～90% 之间：')
eq('1200 ≤ SOC_t ≤ 10800,  t = 1, 2, …, 145', 4)
body('（4）充放电功率限幅约束。变流器最大充放电功率为 P_inv = 5000 kW，'
     '折算到 Δt = 1/6 h 时段的电量上限为 833.33 kWh：')
eq('0 ≤ ch_t ≤ 833.33,  0 ≤ dis_t ≤ 833.33,  t = 1, 2, …, 144', 5)
body('需要说明的是，模型未显式禁止同一时段既充电又放电，但由于 η < 1，'
     '同时充放电会造成净能量损耗而不产生任何收益，最优解自动满足 ch_t·dis_t = 0（数值解验证了这一点：'
     '同时充放电量上界为 0）。')
body('（5）日循环约束。题目要求 0:00 与 24:00 储电量相同，即')
eq('SOC_{145} = SOC_1', 6)
body('该约束保证调度策略可以逐日循环执行，避免“末日放空”的短视行为。')
body('（6）购电量非负约束：')
eq('buy_t ≥ 0,  t = 1, 2, …, 144', 7)
h2('5.4 模型汇总')
body('综上所述，问题一的完整优化模型为如下线性规划：')
eq('min  C = Σ_{t=1}^{144} p_t·buy_t')
body('s.t.  buy_t + PV_t·Δt + dis_t ≥ L_t·Δt + ch_t,  t = 1,…,144；', indent=False)
body('SOC_{t+1} = SOC_t + 0.9·ch_t − dis_t/0.9,  t = 1,…,144；', indent=False)
body('1200 ≤ SOC_t ≤ 10800,  t = 1,…,145；', indent=False)
body('0 ≤ ch_t ≤ 833.33,  0 ≤ dis_t ≤ 833.33,  buy_t ≥ 0,  t = 1,…,144；', indent=False)
body('SOC_{145} = SOC_1。', indent=False)
body('该模型共有 577 个决策变量、144 个不等式约束与 145 个等式约束，目标函数与约束均为线性，'
     '属于凸规划，任意局部最优解即全局最优解。')
h2('5.5 求解方法')
body('模型采用 Python 3 编程实现，调用 scipy.optimize.linprog 函数[14]并指定 HiGHS 求解器[17]'
     '（method = "highs"）。具体地：由附件 1 读入 144 个时段的电价 p_t、小区负载功率 L_t '
     '与光伏预测功率 PV_t，功率乘以 Δt 折算为时段电量；以稀疏矩阵（scipy.sparse.lil_matrix/csr）'
     '构造约束系数矩阵 A_ub、A_eq 及右端向量；调用 linprog 求得全局最优解后，'
     '对解进行功率平衡残差、SOC 上下限与日循环约束的数值校验（残差量级均不超过 10⁻⁶），'
     '并将完整策略写入 result1.xlsx。单日模型求解耗时在毫秒级。')
