h1('七、问题三的模型建立与求解')
h2('7.1 滚动时域调度框架与预报约定')
body('问题三中，光伏出力不再准确已知：每天 0:00 只能获得当日 24 小时的光伏预报功率，'
     '且在 6:00、12:00、18:00 可获得更新后的当日剩余时段预报。调度采用滚动时域（MPC）框架：'
     '每天 0:00 依据当日 24 小时预报求解全天 LP，形成计划购电量 plan_t；'
     '在 6:00、12:00、18:00 三个更新时刻，用最新预报重新求解剩余时段的 LP，'
     '并锁定下一个 6 小时交割区间（0:00—6:00、6:00—12:00、12:00—18:00、18:00—24:00 共四个区间）'
     '的调整购电量 adj_t；区间内的交割量一旦锁定不再更改。'
     '0:00 的预报恰好完整覆盖当日，故全天计划直接由 0:00 预报确定。')
h2('7.2 决策变量')
body('每日的决策变量包括：计划购电量 plan_t、调整购电量 adj_t、充电量 ch_t、放电量 dis_t、'
     '辅助变量 SOC_t（t = 1, 2, …, 144）；事后平衡阶段引入紧急购电量 e_t。'
     '为处理“调整后购电量相对计划量可多可少”的双向偏差，引入非负辅助变量 u_t、v_t，'
     '分别表示上调量与下调量。')
h2('7.3 目标函数')
body('调整购电按交割时刻电价计费：相对计划量上调部分按 1.5 倍电价补差价，下调部分按 0.5 倍电价退还，'
     '另加紧急购电费用。第 d 日目标函数为：')
eq('min  C_d = Σ p_t·plan_t + Σ 1.5·p_t·u_t − Σ 0.5·p_t·v_t + Σ 5·p_t·e_t', 11)
body('其中偏差关系 adj_t − plan_t = u_t − v_t（u_t, v_t ≥ 0）为线性化表达：'
     '由于上调惩罚系数 1.5 严格大于下调回退系数 0.5，二者之差 (1.5−0.5)·p_t > 0，'
     '最优解中 u_t 与 v_t 不会同时为正，该线性化与原分段计价等价。')
h2('7.4 约束条件与事后平衡')
body('滚动重解阶段的约束与问题一相同：以调整购电量 adj_t 替换 buy_t 的功率平衡约束、'
     'SOC 递推式 (3)、电量上下限式 (4)、充放电功率限幅式 (5)，以及跨天 SOC 传递式 (10)；'
     '每个交割区间锁定后，该区间内的 adj_t、ch_t、dis_t 固定为已交割值，后续时刻仅对剩余时段优化。'
     '当日结束后，用光伏实际功率对全天作事后平衡核算：')
eq('adj_t + PV_{实际,t}·Δt + dis_t + e_t ≥ L_t·Δt + ch_t,  t = 1,…,144', 12)
body('实际出力低于预报造成的供电缺口由紧急购电量 e_t 补足，并按 5 倍电价计入总费用；'
     '实际出力高于预报的富余部分予以弃光。全天实际总电费为计划购电费、调整差价与紧急购电费之和。')
